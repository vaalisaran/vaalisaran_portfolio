def h(text, size=16):
    pdf.set_font("Helvetica", "B", size)
    pdf.set_text_color(20, 20, 40)
    pdf.cell(0, 8, text, new_x="LMARGIN", new_y="NEXT")

def body(text):
    pdf.set_x(14)
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(30, 30, 40)
    pdf.multi_cell(182, 5, text)

